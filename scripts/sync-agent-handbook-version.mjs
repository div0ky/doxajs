import { readFile, writeFile } from 'node:fs/promises'

const packageMetadata = JSON.parse(
  await readFile(new URL('../packages/gnosis/package.json', import.meta.url), 'utf8'),
)
const handbookUrl = new URL('../docs/guides/doxa-agent-handbook.md', import.meta.url)
const handbook = await readFile(handbookUrl, 'utf8')
const marker =
  /Generated from the canonical handbook bundled with `@doxajs\/gnosis` [^.\s]+(?:\.[^.\s]+)*\. Do not edit this file independently\./
const replacement = `Generated from the canonical handbook bundled with \`@doxajs/gnosis\` ${packageMetadata.version}. Do not edit this file independently.`

if (!marker.test(handbook)) {
  throw new Error('Could not find the generated Doxa Agent Handbook version marker.')
}

await writeFile(handbookUrl, handbook.replace(marker, replacement))
