import { access, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const RELEASE_CANDIDATE_PATH = '.changeset/release-candidate.json'
const HANDBOOK_PATH = 'docs/guides/doxa-agent-handbook.md'
const PUBLIC_PACKAGE_PREFIX = '@doxajs/'
const VERSION_PATTERN = /^\d+\.\d+\.\d+-alpha\.\d+$/
const HANDBOOK_MARKER =
  /Generated from the canonical handbook bundled with `@doxajs\/gnosis` [^.\s]+(?:\.[^.\s]+)*\. Do not edit this file independently\./
const DEPENDENCY_FIELDS = [
  'dependencies',
  'devDependencies',
  'optionalDependencies',
  'peerDependencies',
]

export async function generateReleaseCandidate(root) {
  const packages = await readPublicPackages(root)
  const version = assertCoordinatedVersions(packages)
  const prerelease = await readJson(path.join(root, '.changeset/pre.json'))
  if (prerelease.mode !== 'pre' || prerelease.tag !== 'alpha') {
    throw new Error('Doxa release candidates require Changesets prerelease mode with tag alpha.')
  }
  await synchronizeHandbookVersion(root, version)
  const candidate = candidateFromPackages(packages, version)
  await writeFile(
    path.join(root, RELEASE_CANDIDATE_PATH),
    `${JSON.stringify(candidate, null, 2)}\n`,
  )
  return candidate
}

export async function validateReleaseCandidate(root, options = {}) {
  const packages = await readPublicPackages(root)
  const version = assertCoordinatedVersions(packages)
  const candidatePath = path.join(root, RELEASE_CANDIDATE_PATH)
  const candidate = await readJson(candidatePath)
  const expected = candidateFromPackages(packages, version)
  if (JSON.stringify(candidate) !== JSON.stringify(expected)) {
    throw new Error(
      `${RELEASE_CANDIDATE_PATH} does not match the coordinated package versions in this commit.`,
    )
  }
  const serialized = await readFile(candidatePath, 'utf8')
  if (serialized !== `${JSON.stringify(expected, null, 2)}\n`) {
    throw new Error(`${RELEASE_CANDIDATE_PATH} is not in canonical generated form.`)
  }

  const prerelease = await readJson(path.join(root, '.changeset/pre.json'))
  if (prerelease.mode !== 'pre' || prerelease.tag !== candidate.channel) {
    throw new Error('The release candidate does not match Changesets prerelease configuration.')
  }

  await assertFixedPackageSet(root, candidate.packages)
  assertInternalDependencyAlignment(packages)
  await assertHandbookVersion(root, version, options.requireBuiltHandbook === true)
  return candidate
}

export async function synchronizeHandbookVersion(root, version) {
  const handbookPath = path.join(root, HANDBOOK_PATH)
  const handbook = await readFile(handbookPath, 'utf8')
  if (!HANDBOOK_MARKER.test(handbook)) {
    throw new Error(`Could not find the generated handbook version marker in ${HANDBOOK_PATH}.`)
  }
  const replacement = `Generated from the canonical handbook bundled with \`@doxajs/gnosis\` ${version}. Do not edit this file independently.`
  await writeFile(handbookPath, handbook.replace(HANDBOOK_MARKER, replacement))
}

export async function readPublicPackages(root) {
  const packagesRoot = path.join(root, 'packages')
  const entries = await readdir(packagesRoot, { withFileTypes: true })
  const packages = []
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const packagePath = path.join(packagesRoot, entry.name, 'package.json')
    if (!(await exists(packagePath))) continue
    const metadata = await readJson(packagePath)
    if (metadata.private === true || !metadata.name?.startsWith(PUBLIC_PACKAGE_PREFIX)) continue
    packages.push({ directory: entry.name, metadata })
  }
  return packages.sort((left, right) => left.metadata.name.localeCompare(right.metadata.name))
}

export function assertCoordinatedVersions(packages) {
  if (packages.length === 0) throw new Error('No public Doxa packages were found.')
  const versions = new Set(packages.map(({ metadata }) => metadata.version))
  if (versions.size !== 1) {
    throw new Error(
      `Doxa packages must publish as one coordinated version; found ${[...versions].join(', ')}.`,
    )
  }
  const [version] = versions
  if (!VERSION_PATTERN.test(version)) {
    throw new Error(`Doxa alpha release version ${version} is not a numbered alpha prerelease.`)
  }
  return version
}

export function assertInternalDependencyAlignment(packages) {
  const packageNames = new Set(packages.map(({ metadata }) => metadata.name))
  for (const { metadata } of packages) {
    for (const field of DEPENDENCY_FIELDS) {
      for (const [name, range] of Object.entries(metadata[field] ?? {})) {
        if (packageNames.has(name) && range !== 'workspace:*') {
          throw new Error(
            `${metadata.name} ${field}.${name} must use workspace:* for coordinated packing.`,
          )
        }
      }
    }
  }
}

function candidateFromPackages(packages, version) {
  return {
    schemaVersion: 1,
    channel: 'alpha',
    version,
    packages: packages.map(({ metadata }) => metadata.name),
  }
}

async function assertFixedPackageSet(root, expectedPackages) {
  const config = await readJson(path.join(root, '.changeset/config.json'))
  const fixedGroups = config.fixed ?? []
  if (fixedGroups.length !== 1) {
    throw new Error('Doxa requires exactly one Changesets fixed package group.')
  }
  const actual = [...fixedGroups[0]].sort()
  const expected = [...expectedPackages].sort()
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error('The Changesets fixed group must contain every public Doxa package.')
  }
}

async function assertHandbookVersion(root, version, requireBuiltHandbook) {
  const handbook = await readFile(path.join(root, HANDBOOK_PATH), 'utf8')
  const expectedMarker = `Generated from the canonical handbook bundled with \`@doxajs/gnosis\` ${version}. Do not edit this file independently.`
  if (!handbook.includes(expectedMarker)) {
    throw new Error(`The public Gnosis handbook is not synchronized to ${version}.`)
  }
  if (!requireBuiltHandbook) return

  const builtHandbookPath = path.join(root, 'packages/gnosis/dist/handbook.js')
  if (!(await exists(builtHandbookPath))) {
    throw new Error('The built Gnosis handbook is missing; run the release package build first.')
  }
  const builtHandbook = await import(`${pathToFileURL(builtHandbookPath).href}?version=${version}`)
  if (handbook !== builtHandbook.renderHandbookMarkdown(version)) {
    throw new Error('The public Gnosis handbook differs from the built canonical handbook.')
  }
}

async function readJson(file) {
  return JSON.parse(await readFile(file, 'utf8'))
}

async function exists(file) {
  try {
    await access(file)
    return true
  } catch {
    return false
  }
}

async function main() {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
  const command = process.argv[2]
  if (command === 'generate') {
    const candidate = await generateReleaseCandidate(root)
    console.log(`Generated ${RELEASE_CANDIDATE_PATH} for ${candidate.version}.`)
    return
  }
  if (command === 'validate') {
    const candidate = await validateReleaseCandidate(root, { requireBuiltHandbook: true })
    console.log(
      `Release candidate ${candidate.version} is coordinated across ${candidate.packages.length} packages.`,
    )
    return
  }
  throw new Error('Usage: node scripts/release-candidate.mjs <generate|validate>')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main()
}
